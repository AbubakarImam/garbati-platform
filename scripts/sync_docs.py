#!/usr/bin/env python3
"""Keep docs/ in sync with the real source files it mirrors or indexes (T-051).

Run by .github/workflows/docs-sync.yml on every push to main that touches
ARCHITECTURE.md, DEPLOYMENT-RUNBOOK.md or research/**. Safe to run locally too
(python3 scripts/sync_docs.py, no third-party dependencies).

Two different jobs live here, for two different reasons:

1. Mirror ARCHITECTURE.md and DEPLOYMENT-RUNBOOK.md into docs/_includes/, byte for byte.

   The original plan (see tasks/T-051-public-docs-site.md) was for docs/architecture.md and
   docs/replicate.md to pull those files directly with Jekyll's `{% include_relative
   ../ARCHITECTURE.md %}` tag, needing no copy and no CI step at all. That was tried first,
   and it does not work: Jekyll's own `IncludeTag#validate_file_name` (shared by `include`
   and `include_relative`) rejects ANY path containing two-or-more consecutive `.` or `/`
   characters via `INVALID_SEQUENCES = /[.\/]{2,}/` - so a `..` segment is refused outright,
   unconditionally, in every Jekyll version checked:
     - the jekyll gem actually installed locally for this task (4.4.1) raises
       "Invalid syntax for include tag. File contains invalid characters or sequences:
       ../ARCHITECTURE.md" the moment `jekyll build` tries to render that tag;
     - GitHub Pages' own pinned Jekyll (3.10.0, per https://pages.github.com/versions.json)
       has the exact same `INVALID_SEQUENCES` check in its `include.rb` (confirmed by reading
       https://raw.githubusercontent.com/jekyll/jekyll/v3.10.0/lib/jekyll/tags/include.rb
       directly), so the real GitHub Pages build would fail identically, not just this local one.
   This is a deliberate, long-standing path-traversal guard, not a bug - safe mode doesn't
   change it, and a symlink into the parent directory doesn't survive Jekyll's own safe-mode
   symlink check for the same reason.

   So instead, this script copies the two real files, unmodified, into docs/_includes/, and
   docs/architecture.md / docs/replicate.md use a plain `{% include %}` (no ".." needed,
   since the mirror now genuinely lives inside docs/). The automatic part moved from "a Liquid
   tag at Jekyll build time" to "a GitHub Action that runs moments before it, on the same
   push" - the owner's actual requirement (edit the real file, the live site updates, with no
   separate manual step) still holds end to end, just with one more hop than first planned.

2. Regenerate docs/_data/research_index.yml from research/*.md.

   research/ sits one directory above docs/ too, and there's no Jekyll tag at all for listing
   an external directory's contents (site.static_files / site.pages only ever see files Jekyll
   read from inside its own `docs/` source - confirmed by an actual build with a scratch page
   looping over site.static_files, which came back empty for anything in research/). A data
   file is the only option here, not a style choice.

Nothing in this file is hand-edited after being written by this script - if it and the real
source files ever disagree, re-run this script (or let the workflow do it on the next push).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

MIRRORED_FILES = {
    ROOT / "ARCHITECTURE.md": DOCS / "_includes" / "architecture.md",
    ROOT / "DEPLOYMENT-RUNBOOK.md": DOCS / "_includes" / "deployment-runbook.md",
}

RESEARCH_DIR = ROOT / "research"
RESEARCH_INDEX_OUT = DOCS / "_data" / "research_index.yml"


def sync_mirrored_files() -> None:
    for source, dest in MIRRORED_FILES.items():
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(source.read_bytes())
        print(f"Mirrored {source.relative_to(ROOT)} -> {dest.relative_to(ROOT)}")


def title_for(path: pathlib.Path) -> str:
    """The file's first top-level Markdown heading, or a fallback built from its name."""
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^#\s+(.*\S)\s*$", line)
        if match:
            return match.group(1)
    return path.stem.replace("-", " ")


def yaml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def regenerate_research_index() -> None:
    files = sorted(RESEARCH_DIR.glob("*.md"))
    lines = [
        "# Generated by scripts/sync_docs.py - do not hand-edit.",
        "# Regenerated automatically by .github/workflows/docs-sync.yml on every push to main",
        "# that touches research/**, so docs/research.md never drifts from the real research/",
        "# directory. See that script's own docstring for why this is a data file instead of",
        "# Jekyll enumerating the directory directly.",
    ]
    for f in files:
        lines.append(f'- filename: "{yaml_escape(f.name)}"')
        lines.append(f'  title: "{yaml_escape(title_for(f))}"')
    RESEARCH_INDEX_OUT.parent.mkdir(parents=True, exist_ok=True)
    RESEARCH_INDEX_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {RESEARCH_INDEX_OUT.relative_to(ROOT)} with {len(files)} entries.")


def main() -> int:
    sync_mirrored_files()
    regenerate_research_index()
    return 0


if __name__ == "__main__":
    sys.exit(main())
